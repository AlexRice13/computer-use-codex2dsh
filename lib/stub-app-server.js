// 助手通过 CODEX_CLI_PATH 启动的 app-server 桩。
// 以无扩展名的 `app-server` CJS 文件写进暂存目录，由复制过去的 node 启动器
// （`codex.exe`）以 argv[1] 拉起。走 stdio 的行分隔 JSON-RPC，行为和
// `codex app-server` 一致。必须同步应答：助手会一直等这个握手，等不到就不
// 接任何电脑操作的 RPC。请求 id 是字符串（"1"），不是数字。
export const STUB_VERSION = 'dsh-1';

const STUB_BODY = `'use strict';
const HOME = process.env.CODEX_HOME || process.env.USERPROFILE || '.';
const CANNED = {
  initialize: {
    userAgent: 'deepseek-harness-computer-use/0.1.0-dsh (win32; x64) codex-computer-use',
    codexHome: HOME,
    platformFamily: 'windows',
    os: 'windows',
  },
  'configRequirements/read': { supportsIndependentSpeedModes: true, requirements: null },
  'config/read': {
    config: {
      computer_use: {
        allow_browser_and_computer_use: true,
        default_app_access: 'allow',
        allow_persistent_approval: true,
        apps: [],
      },
      browser_use: null,
    },
  },
  getAuthStatus: { authMethod: null, accountId: null },
};
let buf = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
  buf += chunk;
  let i;
  while ((i = buf.indexOf('\\n')) >= 0) {
    const line = buf.slice(0, i).trim();
    buf = buf.slice(i + 1);
    if (!line) continue;
    let msg;
    try { msg = JSON.parse(line); } catch { continue; }
    if (msg === null || typeof msg !== 'object' || typeof msg.method !== 'string') continue;
    if (typeof msg.id !== 'number' && !(typeof msg.id === 'string' && msg.id !== '')) continue;
    const result = Object.prototype.hasOwnProperty.call(CANNED, msg.method) ? CANNED[msg.method] : {};
    try { process.stdout.write(JSON.stringify({ id: msg.id, result }) + '\\n'); } catch { process.exit(0); }
  }
});
process.stdin.on('end', () => process.exit(0));
`;

export function stubSource() {
  return `// app-server stub ${STUB_VERSION} — regenerated by dsh-computer-use-sky; edit the plugin, not this file.\n${STUB_BODY}`;
}
